#!/usr/bin/env python3
"""Write tests/openvr_stand_in.hpp from third_party/openvr/openvr.h (1.0.0.11).

The stand-in implements every method of SteamVR's IVRSystem and IVRCompositor as doing nothing
(zero, false or null), so a test can hand the client's own code a runtime and override only what
it needs (tests/video_pass_tests.cpp: the output device, the Vulkan extensions and Submit). Run it
again if the OpenVR headers change; the test build fails while the stand-in is out of date.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEADER = ROOT / 'third_party' / 'openvr' / 'openvr.h'
OUTPUT = ROOT / 'tests' / 'openvr_stand_in.hpp'
INTERFACES = (('IVRSystem', 'System'), ('IVRCompositor', 'Compositor'))


def body(source, name):
    start = source.index('{', source.index('class ' + name + '\n'))
    depth = 0
    for index in range(start, len(source)):
        if source[index] == '{':
            depth += 1
        elif source[index] == '}':
            depth -= 1
            if depth == 0:
                return source[start + 1:index]
    raise SystemExit('unbalanced class ' + name)


def methods(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    text = re.sub(r'//[^\n]*', '', text)
    for declaration in re.findall(r'virtual\s+(.*?)\s*=\s*0\s*;', text, flags=re.S):
        declaration = ' '.join(declaration.split())
        returns = declaration[:declaration.index('(')].rsplit(' ', 1)[0].strip()
        yield declaration, returns == 'void'


def main():
    source = HEADER.read_text(encoding='utf-8')
    lines = ['// Generated by tests/make_openvr_stand_in.py from third_party/openvr/openvr.h; do not edit.',
             "// The method declarations are OpenVR's (Copyright Valve Corporation, BSD 3-Clause:",
             '// third_party/openvr/LICENSE). Every method of IVRSystem and IVRCompositor here does nothing',
             '// (returns zero, false or null); tests derive from these classes and override what they need.',
             '#pragma once', '#include "openvr.h"', '',
             '#if defined(__GNUC__) || defined(__clang__)', '#pragma GCC diagnostic push',
             '#pragma GCC diagnostic ignored "-Wunused-parameter"', '#endif', '',
             'namespace vr {', 'namespace stand_in {']
    for interface, name in INTERFACES:
        lines += ['class ' + name + ' : public ' + interface + ' {', 'public:']
        count = 0
        for declaration, void in methods(body(source, interface)):
            lines.append('  ' + declaration + ' override { ' + ('' if void else 'return {}; ') + '}')
            count += 1
        if count < 20:
            raise SystemExit(interface + ': only ' + str(count) + ' methods found')
        lines += ['};', '']
    lines += ['} // namespace stand_in', '} // namespace vr', '',
              '#if defined(__GNUC__) || defined(__clang__)', '#pragma GCC diagnostic pop', '#endif', '']
    text = '\n'.join(lines)
    if '--check' in sys.argv[1:]:
        if OUTPUT.read_text(encoding='utf-8') != text:
            raise SystemExit(str(OUTPUT) + ' is out of date: run tests/make_openvr_stand_in.py')
        return
    OUTPUT.write_text(text, encoding='utf-8')


if __name__ == '__main__':
    main()
